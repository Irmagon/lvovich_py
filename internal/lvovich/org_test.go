package lvovich

import "testing"

func TestOrgDecline(t *testing.T) {
	tests := []struct {
		name string
		in   string
		dec  string
		want string
	}{
		// Родовое слово + кавычки (типографские)
		{"ООО Ромашка, род. падеж", "ООО «Ромашка»", "genitive", "ООО «Ромашки»"},
		{"ООО Ромашка, дат. падеж", "ООО «Ромашка»", "dative", "ООО «Ромашке»"},
		{"ООО Ромашка, вин. падеж", "ООО «Ромашка»", "accusative", "ООО «Ромашку»"},
		{"ООО Ромашка, твор. падеж", "ООО «Ромашка»", "instrumental", "ООО «Ромашкой»"},
		{"ООО Ромашка, предл. падеж", "ООО «Ромашка»", "prepositional", "ООО «Ромашке»"},

		// Родовое слово + кавычки (ASCII)
		{"ООО Ромашка, ASCII кавычки, род. падеж", "ООО \"Ромашка\"", "genitive", "ООО \"Ромашки\""},

		// Без кавычек
		{"ООО Ромашка без кавычек, род. падеж", "ООО Ромашка", "genitive", "ООО Ромашки"},

		// Родовое слово женского рода
		{"Компания Свет, род. падеж", "компания «Свет»", "genitive", "компания «Света»"},

		// Родовое слово мужского рода
		{"Банк Открытие, род. падеж", "банк «Открытие»", "genitive", "банк «Открытия»"},

		// Склоняемое название-мужского рода без родового слова
		{"Сбербанк, род. падеж", "Сбербанк", "genitive", "Сбербанка"},

		// Несклоняемая аббревиатура
		{"МТС, род. падеж", "МТС", "genitive", "МТС"},

		// Аббревиатура с родовым словом
		{"ПАО МТС, род. падеж", "ПАО «МТС»", "genitive", "ПАО «МТС»"},

		// Многословное название
		{"Красное и белое, род. падеж", "«Красное и белое»", "genitive", "«Красного и белого»"},

		// Имя собственное внутри названия
		{"Имени Ленина, род. падеж", "завод имени Ленина", "genitive", "завод имени Ленина"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := OrgDecline(tt.in, tt.dec)
			if got != tt.want {
				t.Errorf("OrgDecline(%q, %q) = %q, want %q", tt.in, tt.dec, got, tt.want)
			}
		})
	}
}

func TestOrgInFromTo(t *testing.T) {
	tests := []struct {
		name string
		in   string
		inW  string
		from string
		to   string
	}{
		{"Ромашка", "ООО «Ромашка»", "ООО «Ромашке»", "ООО «Ромашки»", "ООО «Ромашку»"},
		{"Сбербанк", "Сбербанк", "Сбербанке", "Сбербанка", "Сбербанк"},
		{"МТС", "МТС", "МТС", "МТС", "МТС"},
		{"Открытие", "банк «Открытие»", "банк «Открытии»", "банк «Открытия»", "банк «Открытие»"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := OrgIn(tt.in); got != tt.inW {
				t.Errorf("OrgIn(%q) = %q, want %q", tt.in, got, tt.inW)
			}
			if got := OrgFrom(tt.in); got != tt.from {
				t.Errorf("OrgFrom(%q) = %q, want %q", tt.in, got, tt.from)
			}
			if got := OrgTo(tt.in); got != tt.to {
				t.Errorf("OrgTo(%q) = %q, want %q", tt.in, got, tt.to)
			}
		})
	}
}